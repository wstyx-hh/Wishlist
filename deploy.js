const fs = require("fs");
const path = require("path");

async function main() {
    const [deployer] = await hre.ethers.getSigners();
    console.log("Deploying contracts with the account:", deployer.address);

    const Wishlist = await hre.ethers.getContractFactory("Wishlist");
    const wishlist = await Wishlist.deploy();
    await wishlist.waitForDeployment(); // Используем этот метод вместо deployed()
    const address = await wishlist.getAddress();
    console.log("Wishlist contract deployed to:", address);

    // Frontend reads the address and ABI from config.js, so it is updated in one place
    const { abi } = await hre.artifacts.readArtifact("Wishlist");
    const config =
        `// Generated by deploy.js (network: ${hre.network.name}). Do not edit by hand.\n` +
        `const contractAddress = '${address}';\n` +
        `const contractABI = ${JSON.stringify(abi, null, 2)};\n`;
    fs.writeFileSync(path.join(__dirname, "config.js"), config);
    console.log("Frontend config written to config.js");
}

main().catch((error) => {
    console.error(error);
    process.exitCode = 1;
});
